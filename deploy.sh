#!/bin/bash
# Deploy this repo onto the PiKVM. Run as root from anywhere.
set -euo pipefail

cd "$(dirname "$(realpath "$0")")"

if [[ $EUID -ne 0 ]]; then
    echo "ERROR: run as root" >&2
    exit 1
fi

REMOUNTED=0
if findmnt -no OPTIONS / | tr ',' '\n' | grep -qx ro; then
    mount -o remount,rw /
    REMOUNTED=1
fi
trap 'if [[ $REMOUNTED -eq 1 ]]; then sync; mount -o remount,ro /; fi' EXIT

#
# One-time migration from the hks401-named install.
#
if [[ -f /etc/systemd/system/hks401d.service ]]; then
    echo "Migrating from hks401 to tesmart ..."
    systemctl disable --now hks401d.service 2>/dev/null || true
    rm -f /etc/systemd/system/hks401d.service \
          /usr/local/bin/hks401d \
          /usr/local/bin/hks401 \
          /usr/local/lib/hks401/hks401.py \
          /usr/local/lib/hks401/hks401.css \
          /usr/local/sbin/install-hks401-kvmd-plugin \
          /etc/kvmd/override.d/hks401.yaml \
          /etc/udev/rules.d/99-hks401-uart.rules
    rm -rf /usr/local/lib/hks401/__pycache__
    rmdir /usr/local/lib/hks401 2>/dev/null || true
    # Older deploys installed the kvmd hook as the generic override.conf.
    OLD_DROPIN=/etc/systemd/system/kvmd.service.d/override.conf
    if [[ -f $OLD_DROPIN ]] && grep -q install-hks401-kvmd-plugin "$OLD_DROPIN"; then
        sed -i '\|install-hks401-kvmd-plugin|d' "$OLD_DROPIN"
        if ! grep -qv -e '^\[Service\]$' -e '^[[:space:]]*$' "$OLD_DROPIN"; then
            rm -f "$OLD_DROPIN"
        fi
    fi
fi

install -Dm0755 daemon/tesmartd                     /usr/local/bin/tesmartd
install -Dm0755 cli/tesmart                         /usr/local/bin/tesmart
install -Dm0755 pikvm/tesmart-kvmd-ui               /usr/local/bin/tesmart-kvmd-ui
install -Dm0644 pikvm/tesmart_uart.py               /usr/local/lib/tesmart/tesmart_uart.py
install -Dm0644 pikvm/web/tesmart.css               /usr/local/lib/tesmart/tesmart.css
install -Dm0755 pikvm/install-tesmart-kvmd-plugin   /usr/local/sbin/install-tesmart-kvmd-plugin
install -Dm0644 systemd/tesmartd.service            /etc/systemd/system/tesmartd.service
install -Dm0644 systemd/kvmd-tesmart.conf           /etc/systemd/system/kvmd.service.d/tesmart.conf
install -Dm0644 udev/99-tesmart-uart.rules          /etc/udev/rules.d/99-tesmart-uart.rules
install -Dm0755 metrics/tesmart-metrics.py          /usr/local/bin/tesmart-metrics.py
install -Dm0644 systemd/tesmart-metrics.service     /etc/systemd/system/tesmart-metrics.service

if [[ ! -f /etc/tesmart.conf ]]; then
    install -Dm0644 tesmart.conf.example /etc/tesmart.conf
    echo "Installed /etc/tesmart.conf (MODEL=auto); edit it to set PIKVM_OUTPUT etc."
fi

# override.yaml is merged after override.d and would replace our view table.
if grep -q -e hks401 -e tesmart /etc/kvmd/override.yaml; then
    echo "WARNING: /etc/kvmd/override.yaml contains hks401/tesmart settings that" >&2
    echo "         take precedence over /etc/kvmd/override.d/tesmart.yaml." >&2
fi

# Keep the serial login service from competing with tesmartd for ttyAMA0.
# systemd-getty-generator can request it because PiKVM boots with
# console=ttyAMA0; masking takes precedence without editing /boot/cmdline.
systemctl mask --now serial-getty@ttyAMA0.service
if [[ "$(systemctl is-enabled serial-getty@ttyAMA0.service)" != "masked" ]]; then
    echo "ERROR: serial getty is not masked" >&2
    exit 1
fi

systemctl daemon-reload
systemctl enable tesmartd.service
systemctl restart tesmartd

# The Prometheus exporter is only useful with node_exporter's textfile
# collector (reading /run/node_exporter), so run it only where that exists.
if systemctl cat node_exporter.service >/dev/null 2>&1; then
    systemctl enable tesmart-metrics.service
    systemctl restart tesmart-metrics.service
else
    echo "node_exporter not installed; tesmart-metrics installed but not enabled."
fi
# kvmd's ExecStartPre runs install-tesmart-kvmd-plugin, which generates
# /etc/kvmd/override.d/tesmart.yaml from tesmartd's model.
systemctl restart kvmd

echo "TESmart deployed: $(head -1 /etc/kvmd/override.d/tesmart.yaml 2>/dev/null | sed 's/^# Generated by tesmart-kvmd-ui for //')"
